class NumberedCanvas(canvas.Canvas):
    """Adds page numbers and academic footer to generated PDF study documents."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_footer(num_pages)
            super().showPage()
        super().save()

    def draw_footer(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 9)
        self.setFillColor(colors.HexColor("#64748b"))
        # Header rule
        self.setStrokeColor(colors.HexColor("#06b6d4"))
        self.setLineWidth(0.5)
        self.line(40, letter[1] - 30, letter[0] - 40, letter[1] - 30)

        # Running header
        self.drawString(40, letter[1] - 25, "F.R.I.D.A.Y. Student Productivity Suite // AI Study Artifact")

        # Footer rule & page number
        self.line(40, 40, letter[0] - 40, 40)
        footer_text = f"Page {self._pageNumber} of {page_count} • Generated by Friday AI Assistant"
        self.drawRightString(letter[0] - 40, 26, footer_text)
        self.drawString(40, 26, datetime.now().strftime("%B %d, %Y"))
        self.restoreState()


class PDFGeneratorService:
    def __init__(self):
        self.output_dir = Path(settings.generated_dir)
        os.makedirs(self.output_dir, exist_ok=True)

    def generate_study_guide(
        self,
        title: str,
        subject: str = "General Studies",
        sections: Optional[List[Dict[str, str]]] = None,
        key_takeaways: Optional[List[str]] = None,
        practice_questions: Optional[List[Dict[str, str]]] = None,
        raw_markdown: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Generates a structured, high-quality academic PDF Study Guide.
        """
        file_id = f"study_guide_{uuid.uuid4().hex[:8]}"
        filename = f"{file_id}.pdf"
        filepath = self.output_dir / filename

        doc = SimpleDocTemplate(
            str(filepath),
            pagesize=letter,
            rightMargin=40,
            leftMargin=40,
            topMargin=45,
            bottomMargin=45
        )

        styles = getSampleStyleSheet()

        # Custom academic styles
        title_style = ParagraphStyle(
            'AcademicTitle',
            parent=styles['Heading1'],
            fontName='Helvetica-Bold',
            fontSize=22,
            leading=26,
            textColor=colors.HexColor("#0f172a"),
            spaceAfter=6
        )

        subtitle_style = ParagraphStyle(
            'AcademicSubtitle',
            parent=styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=11,
            leading=14,
            textColor=colors.HexColor("#0284c7"),
            spaceAfter=15
        )

        heading_style = ParagraphStyle(
            'AcademicH2',
            parent=styles['Heading2'],
            fontName='Helvetica-Bold',
            fontSize=14,
            leading=18,
            textColor=colors.HexColor("#1e293b"),
            spaceBefore=14,
            spaceAfter=8,
            keepWithNext=True
        )

        body_style = ParagraphStyle(
            'AcademicBody',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=10,
            leading=15,
            textColor=colors.HexColor("#334155"),
            spaceAfter=8
        )

        bullet_style = ParagraphStyle(
            'AcademicBullet',
            parent=body_style,
            leftIndent=15,
            firstLineIndent=-10,
            spaceAfter=4
        )

        callout_style = ParagraphStyle(
            'AcademicCallout',
            parent=body_style,
            fontName='Helvetica-Oblique',
            fontSize=9.5,
            leading=14,
            textColor=colors.HexColor("#0369a1")
        )

        story = []

        # Document Header
        story.append(Paragraph(title, title_style))
        story.append(Paragraph(f"Subject: {subject} • Academic Revision Pack", subtitle_style))
        story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#0284c7"), spaceAfter=14))

        # Key Takeaways Box
        if key_takeaways:
            story.append(Paragraph("📌 Executive Key Takeaways", heading_style))
            callout_data = []
            for item in key_takeaways:
                p = Paragraph(f"• {item}", callout_style)
                callout_data.append([p])
            t = Table(callout_data, colWidths=[letter[0] - 80])
            t.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#f0f9ff")),
                ('BOX', (0, 0), (-1, -1), 1, colors.HexColor("#bae6fd")),
                ('TOPPADDING', (0, 0), (-1, -1), 6),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
                ('LEFTPADDING', (0, 0), (-1, -1), 12),
                ('RIGHTPADDING', (0, 0), (-1, -1), 12),
            ]))
            story.append(t)
            story.append(Spacer(1, 14))

        # Core Sections
        if sections:
            for sec in sections:
                sec_title = sec.get("title", "Core Concepts")
                sec_content = sec.get("content", "")
                story.append(Paragraph(sec_title, heading_style))

                # Split content into paragraphs
                paragraphs = sec_content.split("\n\n")
                for p_text in paragraphs:
                    p_clean = p_text.strip()
                    if not p_clean:
                        continue
                    if p_clean.startswith("- ") or p_clean.startswith("* "):
                        for b_line in p_clean.split("\n"):
                            line_clean = b_line.lstrip("-* ").strip()
                            if line_clean:
                                story.append(Paragraph(f"• {line_clean}", bullet_style))
                    else:
                        story.append(Paragraph(p_clean, body_style))
                story.append(Spacer(1, 8))

        # If raw markdown is provided and no sections
        elif raw_markdown:
            story.append(Paragraph("Structured Study Notes", heading_style))
            for block in raw_markdown.split("\n\n"):
                block = block.strip()
                if not block:
                    continue
                if block.startswith("### "):
                    story.append(Paragraph(block[4:], heading_style))
                elif block.startswith("## "):
                    story.append(Paragraph(block[3:], heading_style))
                elif block.startswith("- ") or block.startswith("* "):
                    for line in block.split("\n"):
                        story.append(Paragraph(f"• {line.lstrip('-* ')}", bullet_style))
                else:
                    story.append(Paragraph(block, body_style))

        # Practice Quizzes / Review Flashcards
        if practice_questions:
            story.append(Spacer(1, 10))
            story.append(Paragraph("🧠 Practice Self-Assessment Quiz", heading_style))
            for i, q in enumerate(practice_questions, 1):
                question_text = q.get("question", "")
                answer_text = q.get("answer", "")
                story.append(Paragraph(f"<b>Q{i}: {question_text}</b>", body_style))
                if answer_text:
                    story.append(Paragraph(f"<i>Answer: {answer_text}</i>", callout_style))
                story.append(Spacer(1, 6))

        try:
            doc.build(story, canvasmaker=NumberedCanvas)
            return {
                "success": True,
                "filename": filename,
                "filepath": str(filepath),
                "download_url": f"{settings.backend_url}/api/study/download/{filename}",
                "title": title
            }
        except Exception as e:
            logger.error(f"Failed to generate study guide PDF: {e}")
            return {"success": False, "error": str(e)}

    def generate_formula_cheat_sheet(
        self,
        title: str,
        subject: str,
        formulas: List[Dict[str, str]]
    ) -> Dict[str, Any]:
        """
        Generates a quick-reference Formula Cheat Sheet PDF with structured table layout.
        """
        file_id = f"cheat_sheet_{uuid.uuid4().hex[:8]}"
        filename = f"{file_id}.pdf"
        filepath = self.output_dir / filename

        doc = SimpleDocTemplate(
            str(filepath),
            pagesize=letter,
            rightMargin=36,
            leftMargin=36,
            topMargin=45,
            bottomMargin=45
        )

        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            'CheatSheetTitle',
            parent=styles['Heading1'],
            fontName='Helvetica-Bold',
            fontSize=20,
            leading=24,
            textColor=colors.HexColor("#0f172a")
        )
        sub_style = ParagraphStyle(
            'CheatSheetSub',
            parent=styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=10,
            textColor=colors.HexColor("#0891b2"),
            spaceAfter=12
        )
        cell_header_style = ParagraphStyle(
            'CellHeader',
            fontName='Helvetica-Bold',
            fontSize=9.5,
            textColor=colors.white
        )
        cell_text_style = ParagraphStyle(
            'CellText',
            fontName='Helvetica',
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#1e293b")
        )
        formula_style = ParagraphStyle(
            'FormulaStyle',
            fontName='Courier-Bold',
            fontSize=9.5,
            leading=12,
            textColor=colors.HexColor("#0369a1")
        )

        story = [
            Paragraph(title, title_style),
            Paragraph(f"Subject: {subject} • Formula & Quick Revision Cheat Sheet", sub_style),
            HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#0891b2"), spaceAfter=12)
        ]

        table_data = [[
            Paragraph("Concept / Variable", cell_header_style),
            Paragraph("Formula / Expression", cell_header_style),
            Paragraph("Key Notes & Units", cell_header_style)
        ]]

        for item in formulas:
            table_data.append([
                Paragraph(item.get("name", ""), cell_text_style),
                Paragraph(item.get("formula", ""), formula_style),
                Paragraph(item.get("notes", ""), cell_text_style)
            ])

        col_widths = [140, 180, letter[0] - 72 - 320]
        t = Table(table_data, colWidths=col_widths, repeatRows=1)
        t.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#0f172a")),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
            ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#f8fafc")]),
            ('TOPPADDING', (0, 0), (-1, -1), 6),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
            ('LEFTPADDING', (0, 0), (-1, -1), 8),
            ('RIGHTPADDING', (0, 0), (-1, -1), 8),
        ]))

        story.append(t)

        try:
            doc.build(story, canvasmaker=NumberedCanvas)
            return {
                "success": True,
                "filename": filename,
                "filepath": str(filepath),
                "download_url": f"{settings.backend_url}/api/study/download/{filename}",
                "title": title
            }
        except Exception as e:
            logger.error(f"Failed to generate formula sheet PDF: {e}")
            return {"success": False, "error": str(e)}

